interface I18nContextType {
  locale: Locale;
  setLocale: (locale: Locale) => Promise<void>;
  t: (key: string, variables?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>('en');

  // Load initial locale from JWT or localStorage
  useEffect(() => {
    const savedLocale = localStorage.getItem('vnc_locale') as Locale;
    if (savedLocale === 'en' || savedLocale === 'ro') {
      setLocaleState(savedLocale);
    } else {
      // Check if token exists and has locale
      const token = localStorage.getItem('vnc_token');
      if (token) {
        try {
          const payload = JSON.parse(atob(token.split('.')[1]));
          if (payload && (payload.locale === 'en' || payload.locale === 'ro')) {
            setLocaleState(payload.locale);
            localStorage.setItem('vnc_locale', payload.locale);
          }
        } catch (e) {}
      }
    }
  }, []);

  const setLocale = async (newLocale: Locale) => {
    setLocaleState(newLocale);
    localStorage.setItem('vnc_locale', newLocale);

    // Persist to backend if token is available
    const token = localStorage.getItem('vnc_token');
    if (token) {
      try {
        await fetch('/vnc-crm/api/auth/users/settings', {
          method: 'PUT',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${token}`,
          },
          body: JSON.stringify({ locale: newLocale }),
        });
      } catch (err) {
        console.error('Failed to update locale setting in backend:', err);
      }
    }
  };

  const t = (key: string, variables?: Record<string, string | number>): string => {
    const dict = translations[locale];
    // Find translation by key (case-insensitive check or direct key check)
    const lowerKey = key.toLowerCase();
    let text = (dict as any)[key] || (dict as any)[lowerKey];

    if (!text) {
      // Fallback to english if not found in current locale
      text = (translations.en as any)[key] || (translations.en as any)[lowerKey] || key;
    }

    if (variables) {
      Object.entries(variables).forEach(([k, v]) => {
        text = text.replace(new RegExp(`{${k}}`, 'g'), String(v));
      });
    }

    return text;
  };

  return React.createElement(I18nContext.Provider, { value: { locale, setLocale, t } }, children);
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error('useI18n must be used within an I18nProvider');
  }
  return context;
};
